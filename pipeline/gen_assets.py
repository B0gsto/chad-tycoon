#!/usr/bin/env python3
"""pipeline/gen_assets.py - write src/shared/Assets.luau from assets/pins.json (never hand-type asset ids).

usage: python3 pipeline/gen_assets.py [--check]     (--check: exit 1 when Assets.luau is out of date, write nothing)

Image pins become Assets.Images["<domain>/<name>"] = "rbxassetid://<id>". Model pins become
Assets.Meshes["<domain>/<name>"] = { id = <first MeshPart's MeshId>, model = <uploaded Model id>, size = Vector3 }.
Image entries in art/assets/<domain>.json that carry "cells": { "Coin": [x, y, w, h], ... } (atlases written by
tools/pack_atlas.py) also become Assets.Icons.Coin = { image = "rbxassetid://<id>", x, y, w, h }: one flat table
keyed by icon name, specs read in sorted file order so a later domain wins a name clash.
Rejected pins are left out (callers fall back to part-built props); Reviewing ones are kept (they load once approved).
The output is formatted with stylua when it is on PATH, so the file is byte-stable and passes stylua --check."""
import glob
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME_DIR = os.path.dirname(HERE)
PINS = os.path.join(GAME_DIR, "assets", "pins.json")
SPECS = os.path.join(GAME_DIR, "art", "assets")
OUT = os.path.join(GAME_DIR, "src", "shared", "Assets.luau")

HEADER = """--!strict
-- GENERATED by pipeline/gen_assets.py from assets/pins.json. Do not edit by hand:
-- upload with `python3 pipeline/upload.py <domain>` (it regenerates this file) or run `python3 pipeline/gen_assets.py`.
-- Images: "rbxassetid://" ids for ImageLabel / Decal / SurfaceAppearance. Meshes: the MeshPart mesh id, the uploaded
-- Model id and its size in studs. Models themselves are cloned through AssetModels (src/shared/AssetModels.luau).
-- Icons: atlas cells by icon name (ImageRectOffset = x, y; ImageRectSize = w, h), read by Kit.icon.

export type Mesh = { id: string, model: string, size: Vector3 }
export type Icon = { image: string, x: number, y: number, w: number, h: number }
"""

FOOTER = """
local Assets = {
	Images = Images,
	Meshes = Meshes,
	Icons = Icons,
}

-- The image id for `key` (e.g. "ui/coin"), or nil when it is not uploaded; callers keep a fallback.
function Assets.image(key: string): string?
	return Images[key]
end

-- The mesh record for `key` (e.g. "props/dumbbell"), or nil when it is not uploaded.
function Assets.mesh(key: string): Mesh?
	return Meshes[key]
end

-- The atlas cell for icon `name` (e.g. "Coin"), or nil when no uploaded atlas holds it.
function Assets.icon(name: string): Icon?
	return Icons[name]
end

-- True when `key` names an uploaded image or mesh.
function Assets.has(key: string): boolean
	return Images[key] ~= nil or Meshes[key] ~= nil
end

return Assets
"""


def lua_str(s):
    return json.dumps(s)  # JSON string escapes are valid Luau string escapes for the characters keys use


def num(n):
    r = round(float(n), 3)
    return str(int(r)) if r == int(r) else repr(r)


def usable(p):
    return p is not None and p.get("moderation") != "Rejected" and bool(p.get("assetId"))


def read_cells():
    """[(pin key, { IconName: [x, y, w, h] })] from art/assets/*.json Image entries with "cells", in sorted file order."""
    out = []
    for path in sorted(glob.glob(os.path.join(SPECS, "*.json"))):
        with open(path) as f:
            doc = json.load(f)
        domain = os.path.splitext(os.path.basename(path))[0]
        items = doc
        if isinstance(doc, dict):
            domain = doc.get("domain", domain)
            items = doc.get("assets", [])
        for it in items if isinstance(items, list) else []:
            if isinstance(it, dict) and it.get("name") and isinstance(it.get("cells"), dict):
                out.append((f"{domain}/{it['name']}", it["cells"]))
    return out


def render(pins, cells=()):
    icons = {}
    for key, table in cells:
        p = pins.get(key)
        if not usable(p) or p.get("kind") != "Image":
            continue
        for name, rect in table.items():
            if not (isinstance(rect, list) and len(rect) == 4):
                raise ValueError(f"{key}: cell {name} must be [x, y, w, h]")
            icons[name] = (int(p["assetId"]), [int(v) for v in rect])
    lines = []
    for name in sorted(icons):
        asset_id, (x, y, w, h) = icons[name]
        lines.append(f'\t[{lua_str(name)}] = {{ image = "rbxassetid://{asset_id}", x = {x}, y = {y}, w = {w}, h = {h} }},')
    images, meshes = [], []
    for key in sorted(pins):
        p = pins[key]
        if not usable(p):
            continue
        if p.get("kind") == "Image":
            images.append(f'\t[{lua_str(key)}] = "rbxassetid://{int(p["assetId"])}",')
        elif p.get("kind") == "Model" and p.get("meshId") and p.get("size"):
            x, y, z = p["size"]
            meshes.append(f'\t[{lua_str(key)}] = {{ id = {lua_str(p["meshId"])}, model = "rbxassetid://{int(p["assetId"])}", '
                          f"size = Vector3.new({num(x)}, {num(y)}, {num(z)}) }},")
    out = HEADER
    out += "\nlocal Images: { [string]: string } = {\n" + "".join(l + "\n" for l in images) + "}\n"
    out += "\nlocal Meshes: { [string]: Mesh } = {\n" + "".join(l + "\n" for l in meshes) + "}\n"
    out += "\nlocal Icons: { [string]: Icon } = {\n" + "".join(l + "\n" for l in lines) + "}\n"
    return out + FOOTER, len(images), len(meshes), len(lines)


def format_lua(text):
    if not shutil.which("stylua"):
        return text
    r = subprocess.run(["stylua", "--search-parent-directories", "--stdin-filepath", OUT, "-"], input=text,
                       capture_output=True, text=True, cwd=GAME_DIR)
    return r.stdout if r.returncode == 0 and r.stdout else text


def main():
    try:
        with open(PINS) as f:
            pins = json.load(f).get("pins", {})
    except FileNotFoundError:
        pins = {}
    text, n_img, n_mesh, n_icon = render(pins, read_cells())
    text = format_lua(text)
    try:
        with open(OUT) as f:
            old = f.read()
    except FileNotFoundError:
        old = None
    if "--check" in sys.argv[1:]:
        if old != text:
            print(f"{os.path.relpath(OUT, GAME_DIR)} is out of date: run python3 pipeline/gen_assets.py")
            return 1
        return 0
    if old != text:
        with open(OUT, "w") as f:
            f.write(text)
    print(f"{os.path.relpath(OUT, GAME_DIR)}: {n_img} image(s), {n_mesh} mesh(es), {n_icon} icon(s)" + ("" if old != text else " (unchanged)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
